"""Builds asfpy64.xll and asfpy32.xll, with MinGW-w64 (Linux or Windows) or with MSVC (Windows).

    python excel/python/xll/build.py [mingw|msvc] [--no-runtime]

Without an argument it takes MinGW-w64 when x86_64-w64-mingw32-gcc is on the PATH, else the C++
tools of Visual Studio (found with vswhere). MinGW needs x86_64-w64-mingw32-gcc and
i686-w64-mingw32-gcc (Debian/Ubuntu: gcc-mingw-w64). Writes the generated sources (boot_py.h, the
slots, asfpy.def) and the add-ins to excel/python/xll/build/, then lists each add-in's exports
and imports. The two add-ins there are kept in git (.gitignore): commit them after each build, with
the copies in excel/python/tests/excel.

Each add-in carries a Python of its bitness: the CPython that runtime.json pins, python.org's
build as published on nuget.org, with the packages runtime.json pins (wheels from PyPI, installed
with this machine's pip for the add-in's platform), all downloaded once to build/downloads and
checked against their SHA-256, and stored as a cabinet in the resource ASFPY_RUNTIME. The add-in
unpacks it the first time it loads. --no-runtime leaves it out: such an add-in needs the setting PythonVenv.

The add-ins carry ASF's version (ASF_VERSION in src/ASF.cls): in their Windows version information
and as the mark ASFPY-VERSION:x.y.z; that studio/update.py reads to compare it with a release.
"""
import hashlib
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import tarfile
import urllib.request
import zipfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "build")
NSLOTS, MAX_ARGS = 2000, 32         # as in asfpy.c and boot.py
EXPORTS = ["xlAutoOpen", "xlAutoClose", "xlAutoFree12", "xlAddInManagerInfo12", "SetExcel12EntryPt", "AsfPy_Root",
           "asfpy_call", "asfpy_reload", "asfpy_packages", "asfpy_run_script", "asfpy_macros",
           "asfpy_console", "asfpy_studio", "asfpy_update", "asfpy_last_error", "asfpy_run_macro"]


def write(name, text):
    with open(os.path.join(OUT, name), "w", newline="\n") as f:
        f.write(text)


def c_string(name, file):
    with open(os.path.join(HERE, file), encoding="utf-8") as f:
        src = f.read()
    lines = ['static const char %s[] =' % name]
    for line in src.splitlines(True):
        lines.append('    "%s"' % line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n"))
    return "\n".join(lines) + ";\n"


def boot_header():
    write("boot_py.h", "/* generated by build.py from boot.py, packages.py, console.py and studio/update.py */\n"
          + c_string("BOOT_PY", "boot.py") + c_string("PACKAGES_PY", "packages.py")
          + c_string("CONSOLE_PY", "console.py") + c_string("UPDATE_PY", "studio/update.py"))


def version():
    """ASF's version (ASF_VERSION in src/ASF.cls): the add-in's, which its updates compare."""
    with open(os.path.join(HERE, "..", "..", "..", "src", "ASF.cls"), encoding="latin-1") as f:
        m = re.search(r'ASF_VERSION As String = "(\d+(?:\.\d+){1,3})"', f.read())
    if not m:
        sys.exit("no ASF_VERSION in src/ASF.cls")
    return m.group(1)


def version_files(ver, carry):
    """version.h (the add-in's version mark) and asfpyNN.rc: the version Explorer shows, and the
    Python the add-in carries."""
    write("version.h", '/* generated by build.py from src/ASF.cls */\n#define ASFPY_VERSION "%s"\n' % ver)
    nums = ",".join((ver.split(".") + ["0"] * 4)[:4])
    for bits in (64, 32):
        write("asfpy%d.rc" % bits, """/* generated by build.py */
1 VERSIONINFO
FILEVERSION %(nums)s
PRODUCTVERSION %(nums)s
FILEOS 0x40004
FILETYPE 0x2
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "FileDescription", "ASF Python: Python in Excel (%(bits)d-bit)"
            VALUE "FileVersion", "%(ver)s"
            VALUE "ProductName", "ASF Python"
            VALUE "ProductVersion", "%(ver)s"
            VALUE "OriginalFilename", "asfpy%(bits)d.xll"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
""" % {"nums": nums, "ver": ver, "bits": bits} + ('ASFPY_RUNTIME RCDATA "runtime%d.cab"\n' % bits if carry else ""))


# --- the Python the add-in carries ---------------------------------------------------------------

LEFT_OUT = ("include/", "libs/", "Lib/ensurepip/")   # C headers, import libraries; pip is installed
CAB_DATE = ((2026 - 1980) << 9) | (1 << 5) | 1        # a fixed date: the same files, the same cabinet


def download(pin):
    """A file of runtime.json (the nuget.org package of a Python, a wheel), downloaded once and
    checked against its SHA-256."""
    path = os.path.join(OUT, "downloads", os.path.basename(pin["url"]))
    if not os.path.isfile(path) or hashlib.sha256(open(path, "rb").read()).hexdigest() != pin["sha256"]:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        print("downloading %s" % pin["url"])
        with urllib.request.urlopen(pin["url"]) as r:
            data = r.read()
        if hashlib.sha256(data).hexdigest() != pin["sha256"]:
            sys.exit("%s: its SHA-256 isn't the one in runtime.json" % pin["url"])
        with open(path, "wb") as f:
            f.write(data)
    return path


def cabinet(files):
    """A Microsoft cabinet of (name, bytes): one MSZIP folder, as cabinet.dll (FDI) reads it.
    Each 32 KB block is compressed on its own; no checksums (0 means none)."""
    data = b"".join(b for _, b in files)
    blocks = []
    for i in range(0, len(data), 32768):
        chunk = data[i:i + 32768]
        z = zlib.compressobj(9, zlib.DEFLATED, -15)
        packed = b"CK" + z.compress(chunk) + z.flush()
        blocks.append(struct.pack("<IHH", 0, len(packed), len(chunk)) + packed)
    entries, offset = [], 0
    for name, b in files:
        # 0xA0: the name is UTF-8 (0x80), archive (0x20)
        entries.append(struct.pack("<IIHHHH", len(b), offset, 0, CAB_DATE, 0, 0xA0)
                       + name.replace("/", "\\").encode("utf-8") + b"\0")
        offset += len(b)
    entries = b"".join(entries)
    files_at = 36 + 8
    data_at = files_at + len(entries)
    body = b"".join(blocks)
    header = struct.pack("<4sIIIIIBBHHHHH", b"MSCF", 0, data_at + len(body), 0, files_at, 0, 3, 1,
                         1, len(files), 0, 0, 0)
    folder = struct.pack("<IHH", data_at, len(blocks), 1)    # 1: MSZIP
    return header + folder + entries + body


def packages(bits, version, wheels):
    """The packages runtime.json pins for a bitness (numpy, pandas, pywin32...), as their files
    under Lib/site-packages: installed by this Python's pip for the add-in's Python and platform,
    as pip itself would there (dist-info with RECORD, so pip can upgrade or remove them later).
    The test suites of numpy and pandas are left out."""
    if not wheels:
        return []
    stage = os.path.join(OUT, "packages%d" % bits)
    shutil.rmtree(stage, ignore_errors=True)
    py = "".join(version.split(".")[:2])
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check", "--root-user-action=ignore",
                    "--no-index", "--no-deps", "--no-compile", "--only-binary=:all:",
                    "--target", stage, "--platform", "win_amd64" if bits == 64 else "win32",
                    "--python-version", version.rsplit(".", 1)[0], "--implementation", "cp",
                    "--abi", "cp" + py, "--abi", "none"] + [download(w) for w in wheels], check=True)
    files = []
    for root, dirs, names in os.walk(stage):
        dirs.sort()
        rel = os.path.relpath(root, stage).replace(os.sep, "/")
        parts = rel.split("/")
        if parts[0] == "bin" or "__pycache__" in parts or (parts[0] in ("numpy", "pandas") and "tests" in parts):
            continue                       # scripts made for this machine; caches; test suites
        for n in sorted(names):
            path = os.path.join(root, n)
            files.append(("Lib/site-packages/" + ("" if rel == "." else rel + "/") + n, open(path, "rb").read()))
    print("packages%d: %s; %d files" % (bits, ", ".join(os.path.basename(w["url"]).split("-")[0] for w in wheels), len(files)))
    return files


def editor_files(pin):
    """The files of the code editor the studio uses (CodeMirror), from the package runtime.json pins."""
    with tarfile.open(download(pin)) as t:
        return [(f, t.extractfile("package/" + f).read()) for f in pin["files"]]


def studio(pins):
    """The studio (studio/) as the package asfpy_studio of the add-in's Python, with its editor."""
    root, files = os.path.join(HERE, "studio"), []
    for path, dirs, names in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in ("__pycache__", "vendor"))
        for n in sorted(names):
            rel = os.path.relpath(os.path.join(path, n), root).replace(os.sep, "/")
            files.append(("Lib/site-packages/asfpy_studio/" + rel, open(os.path.join(path, n), "rb").read()))
    if "studio" in pins:
        files += [("Lib/site-packages/asfpy_studio/static/vendor/codemirror/" + f, b) for f, b in editor_files(pins["studio"])]
    return files


def studio_vendor():
    """--studio-vendor: the editor's files into studio/static/vendor, to run the studio from the
    sources (its tests, or python -m with studio/ on the path)."""
    with open(os.path.join(HERE, "runtime.json"), encoding="utf-8") as f:
        pins = json.load(f)
    for name, data in editor_files(pins["studio"]):
        path = os.path.join(HERE, "studio", "static", "vendor", "codemirror", name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    print("studio/static/vendor/codemirror: %d files" % len(pins["studio"]["files"]))


def runtime():
    """The cabinets of both bitnesses (runtime64.cab, runtime32.cab), their resource scripts, and
    runtime.h with the folder each unpacks to: the version, the bitness and the cabinet's hash."""
    with open(os.path.join(HERE, "runtime.json"), encoding="utf-8") as f:
        pins = json.load(f)
    folders = {}
    for bits in (64, 32):
        files = []
        with zipfile.ZipFile(download(pins[str(bits)])) as z:
            for item in sorted(z.infolist(), key=lambda i: i.filename):
                name = item.filename
                if not name.startswith("tools/") or name.endswith("/"):
                    continue
                name = name[len("tools/"):]
                if name.startswith(LEFT_OUT) or "__pycache__/" in name:
                    continue
                files.append((name, z.read(item)))
        files += packages(bits, pins["version"], pins.get("packages", {}).get(str(bits), []))
        files += studio(pins)
        cab = cabinet(files)
        folders[bits] = "python-%s-%d-%s" % (pins["version"], bits, hashlib.sha256(cab).hexdigest()[:12])
        with open(os.path.join(OUT, "runtime%d.cab" % bits), "wb") as f:
            f.write(cab)
        print("runtime%d.cab: %d files, %d bytes; unpacks to %%LOCALAPPDATA%%\\ASF\\runtime\\%s"
              % (bits, len(files), len(cab), folders[bits]))
    write("runtime.h", '/* generated by build.py: the folder the Python of the add-in unpacks to */\n'
          '#ifdef _WIN64\n#define RUNTIME_FOLDER L"%s"\n#else\n#define RUNTIME_FOLDER L"%s"\n#endif\n'
          % (folders[64], folders[32]))


def slots_x64():
    params = ", ".join("LPXLOPER12 a%d" % i for i in range(MAX_ARGS))
    args = ", ".join("a%d" % i for i in range(MAX_ARGS))
    # the caller cleans the stack: one signature serves every number of arguments. A slot reads
    # all MAX_ARGS argument places, so it relies on the caller having that much stack above the
    # call (256 bytes), as Excel, deep in its own frames, always has
    out = ["/* generated by build.py: the exported slots of 64-bit Excel */"]
    for n in range(NSLOTS):
        out.append("EXPORT LPXLOPER12 WINAPI asfpy_f%04d(%s) { LPXLOPER12 v[%d] = { %s }; return asfpy_dispatch(%d, v); }"
                   % (n, params, MAX_ARGS, args, n))
    write("slots_x64.h", "\n".join(out) + "\n")


# __stdcall: the callee removes its arguments. Each slot puts its number in eax and jumps to
# common, which calls asfpy_dispatch(slot, pointer to the arguments) and then returns past the
# slot's registered arguments: 4 bytes each, from asfpy_nargs.
COMMON_X86 = ["push ebp",
              "mov ebp, esp",
              "push ebx",
              "mov ebx, eax",
              "lea ecx, [ebp+8]",
              "push ecx",
              "push ebx",
              "call {dispatch}",
              "add esp, 8",
              "mov ecx, DWORD PTR {nargs}[ebx*4]",
              "pop ebx",
              "pop ebp",
              "pop edx",
              "lea esp, [esp+ecx*4]",
              "jmp edx"]


def slots_x86():
    """MinGW's 32-bit slots, in GNU assembler; the .drectve section exports their plain names."""
    out = ["/* generated by build.py: the exported slots of 32-bit Excel, for MinGW */",
           "    .intel_syntax noprefix",
           "    .text"]
    for n in range(NSLOTS):
        out += ["    .globl _asfpy_f%04d" % n, "_asfpy_f%04d:" % n, "    mov eax, %d" % n, "    jmp _asfpy_common"]
    out += ["_asfpy_common:"]
    out += ["    " + i.format(dispatch="_asfpy_dispatch", nargs="_asfpy_nargs") for i in COMMON_X86]
    out += ["    .section .drectve"]
    out += ['    .ascii " -export:asfpy_f%04d"' % n for n in range(NSLOTS)]
    write("slots_x86.S", "\n".join(out) + "\n")


def slots_x86_msvc():
    """MSVC's 32-bit slots: the same instructions as naked functions with inline assembly."""
    out = ["/* generated by build.py: the exported slots of 32-bit Excel, for MSVC (asfpy.def exports them) */",
           "__declspec(naked) static void asfpy_common(void)",
           "{"]
    out += ["    __asm %s" % i.format(dispatch="asfpy_dispatch", nargs="asfpy_nargs") for i in COMMON_X86]
    out += ["}"]
    for n in range(NSLOTS):
        out.append("__declspec(naked) void asfpy_f%04d(void) { __asm mov eax, %d __asm jmp asfpy_common }" % (n, n))
    write("slots_x86_msvc.h", "\n".join(out) + "\n")


def def_file():
    """The plain export names, for MSVC in both bitnesses (32-bit would decorate them)."""
    names = EXPORTS + ["asfpy_f%04d" % n for n in range(NSLOTS)]
    write("asfpy.def", "EXPORTS\n" + "".join("    %s\n" % n for n in names))


# --- toolchains ---------------------------------------------------------------------------------

def vcvarsall():
    """vcvarsall.bat of the newest Visual Studio with the C++ tools, or None."""
    vswhere = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                           "Microsoft Visual Studio", "Installer", "vswhere.exe")
    if not os.path.isfile(vswhere):
        return None
    # newest first; not -requires, whose component names differ between editions (Build Tools)
    paths = subprocess.run([vswhere, "-all", "-products", "*", "-sort", "-property", "installationPath"],
                           capture_output=True, text=True).stdout.split("\n")
    for path in (p.strip() for p in paths if p.strip()):
        bat = os.path.join(path, "VC", "Auxiliary", "Build", "vcvarsall.bat")
        if os.path.isfile(bat) and os.path.isdir(os.path.join(path, "VC", "Tools", "MSVC")):
            return bat
    return None


def toolchain(name=None):
    if name in ("mingw", "msvc"):
        return name
    if name:
        sys.exit("unknown toolchain %r: mingw or msvc" % name)
    if shutil.which("x86_64-w64-mingw32-gcc"):
        return "mingw"
    if os.name == "nt" and vcvarsall():
        return "msvc"
    sys.exit("no C compiler: install MinGW-w64 (gcc-mingw-w64) or the C++ build tools of Visual Studio")


_msvc_envs = {}


def msvc_env(bits):
    """The environment vcvarsall.bat sets for 64-bit (x64) or 32-bit (x86) targets."""
    if bits not in _msvc_envs:
        out = subprocess.run('"%s" %s >nul && set' % (vcvarsall(), "x64" if bits == 64 else "x86"),
                             shell=True, capture_output=True, text=True, check=True).stdout
        _msvc_envs[bits] = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
    return _msvc_envs[bits]


def msvc_run(bits, args, **kw):
    """Runs a tool of MSVC (cl, dumpbin) in its environment. Windows looks programs up on the
    caller's PATH, not the child's, so the tool is found here first."""
    env = msvc_env(bits)
    path = next(v for k, v in env.items() if k.upper() == "PATH")
    tool = shutil.which(args[0], path=path)
    if not tool:
        sys.exit("%s not found by vcvarsall" % args[0])
    return subprocess.run([tool] + args[1:], env=env, check=True, **kw)


MSVC_FLAGS = ["/nologo", "/O2", "/W3", "/MT", "/utf-8", "/std:c17", "/D_CRT_SECURE_NO_WARNINGS"]


def exports_and_imports(tool, bits, target):
    if tool == "mingw":
        gcc = "x86_64-w64-mingw32-objdump" if bits == 64 else "i686-w64-mingw32-objdump"
        dump = subprocess.run([gcc, "-p", target], check=True, capture_output=True, text=True).stdout
        exports = [l.split()[-1] for l in dump.splitlines()
                   if l.strip().startswith("[") and "+base" not in l and l.split()[-1].isidentifier() and l.split()[-1] != "Table"]
        imports = sorted({l.split(":")[1].strip() for l in dump.splitlines() if l.strip().startswith("DLL Name:")})
        return exports, imports
    dump = msvc_run(bits, ["dumpbin", "/nologo", "/exports", target], capture_output=True, text=True).stdout
    # rows of: ordinal, hint, RVA (8 hex digits), name
    rows = [l.split() for l in dump.splitlines()]
    exports = [t[3] for t in rows if len(t) == 4 and t[0].isdigit() and len(t[2]) == 8
               and all(c in "0123456789ABCDEFabcdef" for c in t[2])]
    dump = msvc_run(bits, ["dumpbin", "/nologo", "/imports", target], capture_output=True, text=True).stdout
    imports = sorted({l.strip() for l in dump.splitlines() if l.strip().lower().endswith(".dll") and " " not in l.strip()})
    return exports, imports


def build(tool, bits, carry):
    target = os.path.join(OUT, "asfpy%d.xll" % bits)
    rc = os.path.join(OUT, "asfpy%d.rc" % bits)
    if tool == "mingw":
        gcc = "x86_64-w64-mingw32-gcc" if bits == 64 else "i686-w64-mingw32-gcc"
        cmd = [gcc, "-O2", "-Wall", "-Wextra", "-Wno-cast-function-type", "-shared", "-static-libgcc",
               "-I", OUT, "-I", HERE, os.path.join(HERE, "asfpy.c")]
        res = os.path.join(OUT, "asfpy%d.res.o" % bits)
        subprocess.run([gcc.replace("gcc", "windres"), "-I", OUT, rc, "-o", res], check=True)
        cmd += (["-DASFPY_RUNTIME"] if carry else []) + [res]
        if bits == 32:
            cmd += [os.path.join(OUT, "slots_x86.S"), "-Wl,--kill-at"]
        cmd += ["-o", target, "-loleaut32", "-lole32", "-ladvapi32", "-luser32", "-lgdi32", "-lcabinet", "-s"]
        subprocess.run(cmd, check=True)
    else:
        obj = os.path.join(OUT, "asfpy%d.obj" % bits)
        res = os.path.join(OUT, "asfpy%d.res" % bits)
        msvc_run(bits, ["rc", "/nologo", "/fo", res, rc], cwd=OUT)
        extra = (["/DASFPY_RUNTIME"] if carry else []) + [res]
        msvc_run(bits, ["cl"] + MSVC_FLAGS + ["/LD", "/DASFPY_DEF", "/I", OUT, "/I", HERE, os.path.join(HERE, "asfpy.c")]
                 + extra + ["/Fo" + obj, "/Fe" + target, "/link", "/DEF:" + os.path.join(OUT, "asfpy.def"),
                            "/IMPLIB:" + os.path.join(OUT, "asfpy%d.lib" % bits),
                            "oleaut32.lib", "ole32.lib", "advapi32.lib", "user32.lib", "gdi32.lib", "cabinet.lib"], cwd=OUT)
    exports, imports = exports_and_imports(tool, bits, target)
    slots = [e for e in exports if e.startswith("asfpy_f")]
    others = [e for e in exports if not e.startswith("asfpy_f")]
    print("%s: %d bytes, %d slots, exports %s, imports %s" % (os.path.basename(target), os.path.getsize(target), len(slots),
                                                              " ".join(others), " ".join(imports)))
    if len(slots) != NSLOTS or sorted(others) != sorted(EXPORTS):
        sys.exit("the exports of %s are wrong" % target)


def main():
    if "--studio-vendor" in sys.argv:
        os.makedirs(OUT, exist_ok=True)
        return studio_vendor()
    args = [a for a in sys.argv[1:] if a != "--no-runtime"]
    carry = "--no-runtime" not in sys.argv
    tool = toolchain(args[0] if args else None)
    os.makedirs(OUT, exist_ok=True)
    boot_header()
    slots_x64()
    slots_x86()
    slots_x86_msvc()
    def_file()
    write("toolchain.txt", tool)     # tests/fakehost/run_fakehost.py builds the fake host with the same
    print("toolchain: %s, version %s" % (tool, version()))
    version_files(version(), carry)
    if carry:
        runtime()
    for bits in (64, 32):
        build(tool, bits, carry)


if __name__ == "__main__":
    main()
