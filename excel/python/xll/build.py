"""Builds asfpy64.xll and asfpy32.xll with MinGW-w64, on Linux or Windows.

    python3 excel/python/xll/build.py

Needs x86_64-w64-mingw32-gcc and i686-w64-mingw32-gcc (Debian/Ubuntu: gcc-mingw-w64). Writes the
generated sources (boot_py.h, slots_x64.h, slots_x86.S) and the add-ins to excel/python/xll/build/,
then lists each add-in's exports and imports.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "build")
NSLOTS, MAX_ARGS = 256, 32          # as in asfpy.c and boot.py


def write(name, text):
    with open(os.path.join(OUT, name), "w", newline="\n") as f:
        f.write(text)


def boot_header():
    with open(os.path.join(HERE, "boot.py"), encoding="utf-8") as f:
        src = f.read()
    lines = ['/* generated by build.py from boot.py */', 'static const char BOOT_PY[] =']
    for line in src.splitlines(True):
        lines.append('    "%s"' % line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n"))
    write("boot_py.h", "\n".join(lines) + ";\n")


def slots_x64():
    params = ", ".join("LPXLOPER12 a%d" % i for i in range(MAX_ARGS))
    args = ", ".join("a%d" % i for i in range(MAX_ARGS))
    # the caller cleans the stack: one signature serves every number of arguments
    out = ["/* generated by build.py: the exported slots of 64-bit Excel */"]
    for n in range(NSLOTS):
        out.append("EXPORT LPXLOPER12 WINAPI asfpy_f%04d(%s) { LPXLOPER12 v[%d] = { %s }; return asfpy_dispatch(%d, v); }"
                   % (n, params, MAX_ARGS, args, n))
    write("slots_x64.h", "\n".join(out) + "\n")


def slots_x86():
    # __stdcall: the callee removes its arguments. Each slot puts its number in eax and jumps to
    # common, which calls asfpy_dispatch and then returns past the slot's registered arguments.
    out = ["/* generated by build.py: the exported slots of 32-bit Excel */",
           "    .intel_syntax noprefix",
           "    .text"]
    for n in range(NSLOTS):
        out += ["    .globl _asfpy_f%04d" % n, "_asfpy_f%04d:" % n, "    mov eax, %d" % n, "    jmp _asfpy_common"]
    out += ["_asfpy_common:",
            "    push ebp",
            "    mov ebp, esp",
            "    push ebx",
            "    mov ebx, eax",
            "    lea ecx, [ebp+8]",
            "    push ecx",
            "    push ebx",
            "    call _asfpy_dispatch",
            "    add esp, 8",
            "    mov ecx, DWORD PTR _asfpy_nargs[ebx*4]",
            "    pop ebx",
            "    pop ebp",
            "    pop edx",
            "    lea esp, [esp+ecx*4]",
            "    jmp edx",
            "    .section .drectve"]
    out += ['    .ascii " -export:asfpy_f%04d"' % n for n in range(NSLOTS)]
    write("slots_x86.S", "\n".join(out) + "\n")


def build(bits):
    gcc = "x86_64-w64-mingw32-gcc" if bits == 64 else "i686-w64-mingw32-gcc"
    target = os.path.join(OUT, "asfpy%d.xll" % bits)
    cmd = [gcc, "-O2", "-Wall", "-Wextra", "-Wno-cast-function-type", "-shared", "-static-libgcc",
           "-I", OUT, "-I", HERE, os.path.join(HERE, "asfpy.c")]
    if bits == 32:
        cmd += [os.path.join(OUT, "slots_x86.S"), "-Wl,--kill-at"]
    cmd += ["-o", target, "-loleaut32", "-lole32", "-ladvapi32", "-s"]
    subprocess.run(cmd, check=True)
    dump = subprocess.run([gcc.replace("gcc", "objdump"), "-p", target], check=True, capture_output=True, text=True).stdout
    exports = [l.split()[-1] for l in dump.splitlines() if l.strip().startswith("[") and "+base" not in l and l.split()[-1].isidentifier() and l.split()[-1] != "Table"]
    imports = sorted({l.split(":")[1].strip() for l in dump.splitlines() if l.strip().startswith("DLL Name:")})
    slots = [e for e in exports if e.startswith("asfpy_f")]
    others = [e for e in exports if not e.startswith("asfpy_f")]
    print("%s: %d bytes, %d slots, exports %s, imports %s" % (os.path.basename(target), os.path.getsize(target), len(slots), " ".join(others), " ".join(imports)))
    if len(slots) != NSLOTS or "xlAutoOpen" not in others or "AsfPy_Root" not in others:
        sys.exit("the exports of %s are wrong" % target)


def main():
    os.makedirs(OUT, exist_ok=True)
    boot_header()
    slots_x64()
    slots_x86()
    for bits in (64, 32):
        build(bits)


if __name__ == "__main__":
    main()
